MODEL_NAME = "2N3904"
# Name used in the .model declaration inside 2n3904.lib and in the netlist.
SPICE_MODEL_NAME = "Q2N3904"
MODEL_PATH = Path(__file__).with_name("spice_models") / "2n3904.lib"

ANALYSES = ("dc", "ac", "tran")

# Baseline CE voltage-divider v1. All values are plain floats; the web layer
# validates and converts form input before building a circuit dict from them.
CIRCUIT_DEFAULTS: dict[str, float] = {
    "vcc": 12.0,
    "r1": 100_000.0,
    "r2": 22_000.0,
    "rc": 2_200.0,
    "re": 1_000.0,
    "rl": 10_000.0,
    "cin": 10e-6,
    "cout": 10e-6,
    "amplitude_v": 0.01,
    "frequency_hz": 1_000.0,
    "ac_start_hz": 10.0,
    "ac_stop_hz": 1_000_000.0,
    "ac_points_dec": 20.0,
}


def format_spice_number(value: float) -> str:
    """Format a finite float as a ngspice-safe number (no grouping commas)."""
    return f"{float(value):.12g}"


def _format_sweep_number(value: float) -> str:
    """Compact form for sweep directives (``1e6`` -> ``1e+06``)."""
    return f"{float(value):g}"


def build_netlist(
    circuit: dict, analysis: str, *, model_path: Path = MODEL_PATH
) -> str:
    """Return one netlist containing only the requested analysis directive."""
    if analysis not in ANALYSES:
        raise ValueError(f"Unknown analysis: {analysis!r}")

    fmt = format_spice_number
    include = Path(model_path).as_posix()

    lines = [
        "* CE voltage-divider amplifier v1 (Lab 04)",
        "* Generated by bjt_bias.spice_engine -- inputs are validated floats only",
        f".include {include}",
        f"VCC  vcc  0   {fmt(circuit['vcc'])}",
        f"R1   vcc  base {fmt(circuit['r1'])}",
        f"R2   base 0   {fmt(circuit['r2'])}",
        f"RC   vcc  coll {fmt(circuit['rc'])}",
        f"RE   emit 0   {fmt(circuit['re'])}",
        f"Q1   coll base emit {SPICE_MODEL_NAME}",
        f"CIN  vin  base {fmt(circuit['cin'])}",
        f"COUT coll out  {fmt(circuit['cout'])}",
        f"RL   out  0    {fmt(circuit['rl'])}",
        (
            "VIN  vin  0   DC 0 AC 1 "
            f"SIN(0 {fmt(circuit['amplitude_v'])} {fmt(circuit['frequency_hz'])})"
        ),
        ".control",
        "set units=degrees",
        # Without this, wrdata repeats the scale column before every vector.
        "set wr_singlescale",
    ]

    if analysis == "dc":
        lines.extend(
            [
                "op",
                "wrdata op.txt v(base) v(emit) v(coll) "
                "@q1[ic] @q1[ib] @q1[ie]",
            ]
        )
    elif analysis == "ac":
        lines.extend(
            [
                "ac dec "
                f"{_format_sweep_number(circuit['ac_points_dec'])} "
                f"{_format_sweep_number(circuit['ac_start_hz'])} "
                f"{_format_sweep_number(circuit['ac_stop_hz'])}",
                "wrdata ac.txt vdb(out) vp(out)",
            ]
        )
    else:
        stop_s = 5.0 / float(circuit["frequency_hz"])
        step_s = stop_s / 1000.0
        lines.extend(
            [
                f"tran {fmt(step_s)} {fmt(stop_s)}",
                "wrdata tran.txt v(vin) v(out)",
            ]
        )

    lines.extend([".endc", ".end", ""])
    return "\n".join(lines)


class SpiceParseError(ValueError):
    """Raised when an ngspice result file does not match the expected layout."""


def _rows(text: str) -> list[list[float]]:
    """Parse whitespace-separated numeric rows, skipping blank/comment lines."""
    rows: list[list[float]] = []
    for lineno, line in enumerate(text.splitlines(), start=1):
        stripped = line.strip()
        if not stripped or stripped[0] in "*#":
            continue
        try:
            values = [float(token) for token in stripped.split()]
        except ValueError as exc:
            raise SpiceParseError(
                f"line {lineno}: expected numeric columns, saw {stripped!r}"
            ) from exc
        if not all(math.isfinite(value) for value in values):
            raise SpiceParseError(f"line {lineno}: non-finite value in {stripped!r}")
        rows.append(values)
    return rows


def parse_op(text: str) -> dict:
    """Parse the single-row ``op.txt`` produced by ``set wr_singlescale``."""
    rows = _rows(text)
    if not rows:
        raise SpiceParseError("op.txt contains no data rows")
    row = rows[0]
    if len(row) == 7:  # scale column + 6 requested vectors
        values = row[1:]
    elif len(row) == 6:
        values = row
    else:
        raise SpiceParseError(f"expected 6 values per row, saw {len(row)}")
    v_b, v_e, v_c, i_c, i_b, i_e = values
    return {
        "v_b_v": v_b,
        "v_e_v": v_e,
        "v_c_v": v_c,
        "v_ce_v": v_c - v_e,
        "i_b_a": i_b,
        "i_c_a": i_c,
        "i_e_a": i_e,
    }


def parse_ac(text: str) -> dict:
    """Parse ``ac.txt``: frequency (Hz), gain (dB), phase (deg)."""
    freq: list[float] = []
    gain: list[float] = []
    phase: list[float] = []
    for lineno, row in enumerate(_rows(text), start=1):
        if len(row) != 3:
            raise SpiceParseError(
                f"line {lineno}: expected 3 values per row, saw {len(row)}"
            )
        freq.append(row[0])
        gain.append(row[1])
        phase.append(row[2])
    return {"freq_hz": freq, "gain_db": gain, "phase_deg": phase}


def parse_tran(text: str) -> dict:
    """Parse ``tran.txt``: time (s), vin (V), vout (V)."""
    time: list[float] = []
    vin: list[float] = []
    vout: list[float] = []
    for lineno, row in enumerate(_rows(text), start=1):
        if len(row) != 3:
            raise SpiceParseError(
                f"line {lineno}: expected 3 values per row, saw {len(row)}"
            )
        time.append(row[0])
        vin.append(row[1])
        vout.append(row[2])
    return {"time_s": time, "vin_v": vin, "vout_v": vout}


def _check_increasing(values: list[float], label: str) -> None:
    for index, (before, after) in enumerate(zip(values, values[1:]), start=2):
        if after <= before:
            raise SpiceParseError(
                f"{label} is not increasing at row {index}: {after} <= {before}"
            )


def parse_ac_safe(text: str) -> dict:
    """Parse an AC sweep with the minimum-row and monotonic-sweep guarantees."""
    data = parse_ac(text)
    count = len(data["freq_hz"])
    if count < 10:
        raise SpiceParseError(f"ac sweep has only {count} rows (need at least 10)")
    _check_increasing(data["freq_hz"], "ac frequency")
    return data


def parse_tran_safe(text: str) -> dict:
    """Parse a transient run with the minimum-row and monotonic-time guarantees."""
    data = parse_tran(text)
    count = len(data["time_s"])
    if count < 100:
        raise SpiceParseError(
            f"transient run has only {count} rows (need at least 100)"
        )
    _check_increasing(data["time_s"], "transient time")
    return data


RUNS_ROOT = Path(__file__).resolve().parent.parent / "runs"
RESULT_FILES = {"dc": "op.txt", "ac": "ac.txt", "tran": "tran.txt"}
PARSERS = {"dc": parse_op, "ac": parse_ac_safe, "tran": parse_tran_safe}
MAX_RESULT_BYTES = 20 * 1024 * 1024
MAX_RESULT_LINES = 200_000
MAX_RUNS = 50
TAIL_LINES = 40


def _model_info() -> dict:
    return {
        "name": MODEL_NAME,
        "spice_name": SPICE_MODEL_NAME,
        "file": MODEL_PATH.name,
        "sha256": hashlib.sha256(MODEL_PATH.read_bytes()).hexdigest(),
    }


def _probe_version(executable: Path, timeout: float) -> tuple[str | None, str]:
    try:
        proc = subprocess.run(
            [str(executable), "--version"],
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=timeout,
            shell=False,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        return None, str(exc)
    text = (proc.stdout or "") + (proc.stderr or "")
    match = re.search(r"ngspice-[0-9][A-Za-z0-9.]*", text)
    if match:
        return match.group(0), None
    return None, "no ngspice version banner in output"


def _candidate_paths(target: str | Path) -> list[Path]:
    path = Path(target)
    if path.is_dir():
        return [
            path / "bin" / "ngspice_con.exe",
            path / "ngspice_con.exe",
            path / "bin" / "ngspice.exe",
            path / "ngspice.exe",
        ]
    return [path]


@functools.lru_cache(maxsize=8)
def locate_engine(timeout: float = 10.0) -> dict:
    """Find a runnable ngspice binary and report why it is unavailable if not.

    When ``NGSPICE_BIN`` is set it is authoritative: an invalid value must not
    silently fall back to a known installation (the browser acceptance case
    B7(b) depends on being able to simulate a missing engine).
    """
    env = os.environ.get("NGSPICE_BIN")
    if env:
        candidates = _candidate_paths(env)
        source = f"NGSPICE_BIN={env}"
    else:
        candidates = []
        for name in ("ngspice_con.exe", "ngspice.exe", "ngspice"):
            found = shutil.which(name)
            if found:
                candidates.append(Path(found))
        candidates.extend(
            [
                Path(r"C:\Tools\ngspice-47\bin\ngspice_con.exe"),
                Path(r"C:\Tools\ngspice-47\bin\ngspice.exe"),
            ]
        )
        source = "PATH or C:\\Tools\\ngspice-47"

    tried: list[str] = []
    for candidate in candidates:
        if not candidate.is_file():
            tried.append(f"{candidate} (missing)")
            continue
        version, error = _probe_version(candidate, timeout)
        if version:
            return {
                "available": True,
                "path": str(candidate),
                "version": version,
                "source": source,
                "error": None,
            }
        tried.append(f"{candidate}: {error}")

    return {
        "available": False,
        "path": None,
        "version": None,
        "source": source,
        "error": f"ngspice not found ({'; '.join(tried) or 'no candidates'})",
    }


def clear_engine_cache() -> None:
    """Forget a cached engine lookup (used after changing NGSPICE_BIN)."""
    locate_engine.cache_clear()


def _tail(text: str, limit: int = TAIL_LINES) -> str:
    return "\n".join(
        [line for line in (text or "").splitlines() if line.strip()][-limit:]
    )


def _as_text(value: object) -> str:
    if isinstance(value, bytes):
        return value.decode("utf-8", errors="replace")
    return value or ""


def _write_meta(run_dir: Path, meta: dict) -> None:
    (run_dir / "meta.json").write_text(
        json.dumps(meta, indent=2, ensure_ascii=False), encoding="utf-8"
    )


def _prune_runs(runs_root: Path, keep: int = MAX_RUNS) -> None:
    try:
        dirs = sorted(
            (path for path in runs_root.iterdir() if path.is_dir()),
            key=lambda path: path.name,
        )
    except OSError:
        return
    for old in dirs[:-keep]:
        shutil.rmtree(old, ignore_errors=True)


def run_analysis(
    circuit: dict,
    analysis: str,
    *,
    runs_root: Path = RUNS_ROOT,
    engine: dict | None = None,
    timeout: float = 60.0,
) -> dict:
    """Run ngspice once and return data only when the run is fully valid."""
    if analysis not in ANALYSES:
        raise ValueError(f"Unknown analysis: {analysis!r}")
    if engine is None:
        engine = locate_engine()
    engine = dict(engine)

    started_at = datetime.now(timezone.utc)
    clock = time.monotonic()
    result: dict = {
        "status": "failed",
        "analysis": analysis,
        "run_id": "",
        "run_dir": "",
        "netlist": "",
        "command": [],
        "returncode": None,
        "duration_s": 0.0,
        "engine": engine,
        "model": _model_info(),
        "data": {},
        "warnings": [],
        "stdout_tail": "",
        "stderr_tail": "",
    }

    if not engine.get("available"):
        result["status"] = "engine_missing"
        result["stderr_tail"] = engine.get("error") or "ngspice not found"
        return result

    root = Path(runs_root)
    root.mkdir(parents=True, exist_ok=True)
    run_id = f"{started_at.strftime('%Y%m%dT%H%M%S')}-{secrets.token_hex(3)}"
    run_dir = root / run_id
    run_dir.mkdir(parents=True, exist_ok=True)

    netlist = build_netlist(circuit, analysis)
    (run_dir / "circuit.cir").write_text(netlist, encoding="utf-8")
    command = [str(engine["path"]), "-b", "-o", "run.log", "circuit.cir"]
    meta = {
        "analysis": analysis,
        "run_id": run_id,
        "started_at": started_at.isoformat(),
        "input": dict(circuit),
        "engine": {"path": engine.get("path"), "version": engine.get("version")},
        "model": result["model"],
        "command": command,
        "timeout_s": timeout,
    }
    _write_meta(run_dir, meta)
    result.update(run_id=run_id, run_dir=str(run_dir), netlist=netlist, command=command)

    status: str | None = None
    returncode: int | None = None
    stdout = ""
    stderr = ""
    try:
        proc = subprocess.run(
            command,
            cwd=run_dir,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=timeout,
            shell=False,
        )
        returncode = proc.returncode
        stdout = _as_text(proc.stdout)
        stderr = _as_text(proc.stderr)
    except subprocess.TimeoutExpired as exc:
        status = "timeout"
        returncode = None
        stdout = _as_text(exc.stdout)
        stderr = (f"ngspice did not finish within {timeout:g} s\n"
                  + _as_text(exc.stderr))
    except OSError as exc:
        status = "failed"
        stderr = f"could not start ngspice at {engine.get('path')}: {exc}"

    log_path = run_dir / "run.log"
    log_text = (
        log_path.read_text("utf-8", errors="replace") if log_path.is_file() else ""
    )
    result["stdout_tail"] = _tail(stdout)
    result["stderr_tail"] = _tail("\n".join([stderr, log_text]))
    result["returncode"] = returncode
    result["duration_s"] = round(time.monotonic() - clock, 3)

    if status is None:
        if returncode != 0:
            status = "failed"
            result["stderr_tail"] = (
                f"ngspice exited with code {returncode}\n" + result["stderr_tail"]
            )
        else:
            result_path = run_dir / RESULT_FILES[analysis]
            try:
                size = result_path.stat().st_size
            except OSError:
                size = 0
            if size == 0:
                status = "parse_error"
                result["stderr_tail"] += f"\nmissing or empty {RESULT_FILES[analysis]}"
            elif size > MAX_RESULT_BYTES:
                status = "parse_error"
                result["stderr_tail"] += (
                    f"\n{RESULT_FILES[analysis]} is larger than "
                    f"{MAX_RESULT_BYTES} bytes"
                )
            else:
                text = result_path.read_text("utf-8", errors="replace")
                if len(text.splitlines()) > MAX_RESULT_LINES:
                    status = "parse_error"
                    result["stderr_tail"] += (
                        f"\n{RESULT_FILES[analysis]} has more than "
                        f"{MAX_RESULT_LINES} rows"
                    )
                else:
                    try:
                        data = PARSERS[analysis](text)
                    except SpiceParseError as exc:
                        status = "parse_error"
                        result["stderr_tail"] += f"\n{exc}"
                    else:
                        status = "ok"
                        result["data"] = data
                        if analysis == "dc":
                            ic_from_rc = (
                                float(circuit["vcc"]) - data["v_c_v"]
                            ) / float(circuit["rc"])
                            if (
                                abs(ic_from_rc - data["i_c_a"])
                                > 0.02 * abs(data["i_c_a"])
                            ):
                                result["warnings"].append(
                                    "IC cross-check differs from "
                                    "(VCC - V(C)) / RC by more than 2%"
                                )

    result["status"] = status or "failed"
    meta.update(
        status=result["status"],
        returncode=returncode,
        duration_s=result["duration_s"],
    )
    _write_meta(run_dir, meta)
    _prune_runs(root)
    return result
